package risk

// 이 파일은 "확신도가 높으면 크게 건다" 를 정한다. risk.go 가 정하는 상한
// (equity × [CapFraction]) 은 그대로 살아 있고, 여기서 나오는 값은 그 **안쪽**
// 에서 목표 크기를 낮추는 쪽으로만 쓰인다.
//
// # 왜 균등이 아닌가
//
// 모델은 확신할수록 과신한다. 2019~2024 106,951회차로 confidence 구간별 실제
// 판정 승률을 재면:
//
//	conf 구간     n        모델 주장    실제      괴리
//	0.14~0.16   30,683    57.48%    56.33%   −1.15%p
//	0.20~0.24   19,494    60.88%    59.66%   −1.22%p
//	0.30~0.40    4,536    66.77%    60.67%   −6.10%p
//	0.40~        1,300    75.02%    60.67%  −14.63%p
//
// 승률은 오르지만 모델 주장만큼은 아니고, 0.30 위에서는 아예 평평해진다.
// confidence 를 그대로 크기에 쓰면 **모델이 가장 크게 틀리는 구간에 가장 크게
// 건다.** 그래서 크기는 confidence 가 아니라 **교정된 승률에서 나온 켈리**에
// 비례시킨다.
//
// # 표의 유래
//
// 교정 승률 q 에서 켈리 비중을 낸다. 판정 승률을 그대로 넣지 않는 것이
// 요점이다 — 우리가 이길 회차는 78.0% 만 체결되고 질 회차는 99.8% 체결되므로
// (오더북 1,714회차 실측), 체결 조건부 승률로 바꿔야 한다:
//
//	fw = q·P(체결|승) / ( q·P(체결|승) + (1−q)·P(체결|패) )
//	f* = ( fw·b − (1−fw) ) / b          b = 0.98/진입가 − 1 = 1.0893
//
// 그 f* 를 최댓값으로 나눠 [0, 1] 로 만든 것이 [confWeights] 다.
//
//	conf 구간     교정승률     켈리 f*    가중치
//	0.10~0.12   54.54%     1.02%    0.0792
//	0.12~0.14   55.27%     2.45%    0.1891
//	0.14~0.16   56.33%     4.50%    0.3479
//	0.16~0.18   57.02%     5.85%    0.4525
//	0.18~0.20   57.77%     7.31%    0.5657
//	0.20~0.24   59.66%    11.05%    0.8545
//	0.24~0.30   60.15%    12.02%    0.9296
//	0.30~       60.61%    12.93%    1.0000
//
// **교정은 2019~2024 로만 만들었다.** 2025·2026 은 손대지 않은 채로 평가했고,
// 2024 를 표본에서 빼고 다시 만든 표로 2024 를 평가해도 결과가 5% 밖에 안
// 달라졌다(누적 +3,647 → +3,471). 과적합 흔적이 없다는 뜻이다.
//
// # 무엇을 기대할 수 있고 무엇을 기대할 수 없나
//
// 매회 상한 50 USDT 로 잰 3년 백테스트(지정가 0.47, 오더북 깊이 반영):
//
//	연도   진입     진입승률   누적손익    최대인출   샤프
//	2024   16,281   54.95%   +3,472    2,417   1.44
//	2025    9,265   54.40%     −761    2,412  −0.49
//	2026    8,608   55.17%   +3,234      966   2.69
//
// 균등 배분(같은 총 명목)보다 샤프가 세 해 모두 높다. 그러나 **2025 는
// 여전히 적자다.** 크기 규칙은 있는 우위를 잘 쓰는 장치이지 없는 우위를
// 만드는 장치가 아니다. 손익분기 판정 승률 54.01% 에 대해 그 해의 여유는
// +0.39%p 뿐이었고, 깊이 역선택(이기는 회차만 물량이 잘린다)이 그것을
// 마이너스로 뒤집었다.

// MaxStakeUSD 는 회차당 목표 명목의 절대 상한이다.
//
// 백테스트는 50 USDT 로 했고 실계좌에는 그 **1/5** 를 넣는다(2026-08-17
// 사용자 결정). 이 값은 [CapFraction] 을 대체하지 않는다 — 둘 중 **작은 쪽**이
// 이긴다. 지금 자본(약 65 USDT)에서는 cap 이 2.96 USDT 라 conf 0.14 위부터는
// cap 이 이기고, 자본이 220 USDT 를 넘어야 이 상한이 전 구간에서 묶는다.
//
// **작게 잡으면 저확신 구간이 최소 주문에 걸려 통째로 사라진다.** 10 USDT
// 에서 각 칸의 목표는 0.79 / 1.89 / 3.48 / 4.53 / 5.66 / 8.55 / 9.30 / 10.00
// USDT 이고, 첫 칸(conf 0.10~0.12)만 [MinOrderUSD] 미만이다. 즉 이 상한에서
// 실효 문턱은 0.12 다 — 문턱 상수는 0.10 이지만 그 아래 칸은 주문이 성립하지
// 않는다. 상한을 올리면 실효 문턱이 함께 내려간다.
const MaxStakeUSD = 10.0

// confBins 는 [confWeights] 각 칸의 **하한**이다. 오름차순이고, 마지막 칸은
// 위가 열려 있다.
//
// 첫 칸이 0.10 인 것은 [live.ConfidenceThreshold] 와 같은 값이다. 그보다 낮은
// confidence 에서는 교정 승률이 손익분기 아래라 켈리가 0 이 되므로, 문턱이
// 없어도 이 표가 스스로 0 을 준다 — 문턱과 이 표는 같은 사실의 두 표현이다.
var confBins = [8]float64{0.10, 0.12, 0.14, 0.16, 0.18, 0.20, 0.24, 0.30}

// confWeights 는 각 칸의 목표 비율이다. 최고 칸이 1.0 이 되도록 정규화돼 있다.
var confWeights = [8]float64{0.0792, 0.1891, 0.3479, 0.4525, 0.5657, 0.8545, 0.9296, 1.0000}

// ConfidenceWeight 는 이 confidence 에서 목표 크기가 상한의 몇 배인지 준다.
// 값은 [0, 1] 이다.
//
// confidence 가 첫 칸 아래면 0 이다 — 그 구간은 교정 승률이 손익분기 아래다.
// NaN·Inf·음수도 0 이다(이 패키지의 규칙: 망가진 입력에서는 거래하지 않는다).
//
// 선형 보간하지 않고 **계단**인 것이 의도다. 표의 각 칸은 수만 회차를 모아
// 잰 평균이고, 칸 안에서 승률이 어떻게 움직이는지는 재지 않았다. 보간은
// 재지 않은 것을 아는 척하는 것이고, 칸 경계에서 크기가 튀는 것은 눈에
// 보이지만 잘못된 보간은 보이지 않는다.
func ConfidenceWeight(confidence float64) float64 {
	if !finite(confidence) || confidence < confBins[0] {
		return 0
	}
	w := 0.0
	for i, lo := range confBins {
		if confidence < lo {
			break
		}
		w = confWeights[i]
	}
	return w
}

// StakeTarget 은 이 confidence 에서 걸고 싶은 명목이다(USD).
//
// **상한이지 보장이 아니다.** 호출자는 이 값과 [Remaining] 중 작은 쪽을 써야
// 한다 — equity 대비 상한은 여전히 risk.go 가 정하고, 이 파일은 그 안쪽에서
// 크기를 낮추는 일만 한다.
//
// 0 을 돌려주면 그 회차는 걸지 않는다.
func StakeTarget(confidence float64) float64 {
	w := ConfidenceWeight(confidence)
	if w <= 0 {
		return 0
	}
	t := MaxStakeUSD * w
	if !finite(t) || t <= 0 {
		return 0
	}
	return t
}
