package risk

// 이 파일은 "확신도가 높으면 크게 건다" 를 정한다. risk.go 가 정하는 상한
// (equity × [CapFraction]) 은 그대로 살아 있고, 여기서 나오는 값은 그 **안쪽**
// 에서 목표 크기를 낮추는 쪽으로만 쓰인다.
//
// # 왜 균등이 아닌가
//
// 모델은 확신할수록 과신한다. 2019~2024 106,951회차로 confidence 구간별 실제
// 판정 승률을 재면:
//
//	conf 구간     n        모델 주장    실제      괴리
//	0.14~0.16   30,683    57.48%    56.33%   −1.15%p
//	0.20~0.24   19,494    60.88%    59.66%   −1.22%p
//	0.30~0.40    4,536    66.77%    60.67%   −6.10%p
//	0.40~        1,300    75.02%    60.67%  −14.63%p
//
// 승률은 오르지만 모델 주장만큼은 아니고, 0.30 위에서는 아예 평평해진다.
// confidence 를 그대로 크기에 쓰면 **모델이 가장 크게 틀리는 구간에 가장 크게
// 건다.** 그래서 크기는 confidence 가 아니라 **교정된 승률에서 나온 켈리**에
// 비례시킨다.
//
// # 표의 유래
//
// 교정 승률 q 에서 켈리 비중을 낸다. 판정 승률을 그대로 넣지 않는 것이
// 요점이다 — 우리가 이길 회차는 78.0% 만 체결되고 질 회차는 99.8% 체결되므로
// (오더북 1,714회차 실측), 체결 조건부 승률로 바꿔야 한다:
//
//	fw = q·P(체결|승) / ( q·P(체결|승) + (1−q)·P(체결|패) )
//	f* = ( fw·b − (1−fw) ) / b          b = 0.98/진입가 − 1 = 1.0893
//
// 그 f* 를 최댓값으로 나눠 [0, 1] 로 만든 것이 [confWeights] 다.
//
//	conf 구간     교정승률     켈리 f*    가중치
//	0.10~0.12   54.54%     1.02%    0.0792
//	0.12~0.14   55.27%     2.45%    0.1891
//	0.14~0.16   56.33%     4.50%    0.3479
//	0.16~0.18   57.02%     5.85%    0.4525
//	0.18~0.20   57.77%     7.31%    0.5657
//	0.20~0.24   59.66%    11.05%    0.8545
//	0.24~0.30   60.15%    12.02%    0.9296
//	0.30~       60.61%    12.93%    1.0000
//
// **교정은 2019~2024 로만 만들었다.** 2025·2026 은 손대지 않은 채로 평가했고,
// 2024 를 표본에서 빼고 다시 만든 표로 2024 를 평가해도 결과가 5% 밖에 안
// 달라졌다(누적 +3,647 → +3,471). 과적합 흔적이 없다는 뜻이다.
//
// # 무엇을 기대할 수 있고 무엇을 기대할 수 없나
//
// 매회 상한 50 USDT 로 잰 3년 백테스트(지정가 0.47, 오더북 깊이 반영):
//
//	연도   진입     진입승률   누적손익    최대인출   샤프
//	2024   16,281   54.95%   +3,472    2,417   1.44
//	2025    9,265   54.40%     −761    2,412  −0.49
//	2026    8,608   55.17%   +3,234      966   2.69
//
// 균등 배분(같은 총 명목)보다 샤프가 세 해 모두 높다. 그러나 **2025 는
// 여전히 적자다.** 크기 규칙은 있는 우위를 잘 쓰는 장치이지 없는 우위를
// 만드는 장치가 아니다. 손익분기 판정 승률 54.01% 에 대해 그 해의 여유는
// +0.39%p 뿐이었고, 깊이 역선택(이기는 회차만 물량이 잘린다)이 그것을
// 마이너스로 뒤집었다.

// MaxStakeUSD 는 회차당 목표 명목의 절대 상한이다.
//
// **회차당 걸 수 있는 최대 금액이다.** 2026-08-17 에 equity 비례 상한
// ([CapFraction])이 크기 결정에서 빠지면서, 이 상수가 그 자리를 대신한다 —
// 자본이 얼마든 한 회차에 이 값보다 크게 걸지 않는다.
//
//	50   백테스트 기준값
//	10   2026-08-17   백테스트의 1/5
//	 5   2026-08-17~  사용자 결정
//
// # 각 칸의 목표
//
// 이 값에 [confWeights] 를 곱하고, [MinStakeUSD] 로 바닥을 깐다:
//
//	conf 구간     켈리 비례   바닥 적용 후
//	0.10~0.12       0.40        1.50 ←
//	0.12~0.14       0.95        1.50 ←
//	0.14~0.16       1.74        1.74
//	0.16~0.18       2.26        2.26
//	0.18~0.20       2.83        2.83
//	0.20~0.24       4.27        4.27
//	0.24~0.30       4.65        4.65
//	0.30~           5.00        5.00
const MaxStakeUSD = 5.0

// MinStakeUSD 는 걸기로 한 회차의 최소 명목이다(2026-08-17 사용자 결정).
//
// # 왜 필요한가
//
// [MaxStakeUSD] 가 5 USDT 라 아래 두 칸의 켈리 비례 목표가 0.40·0.95 USDT
// 가 되는데, 둘 다 거래소 최소 주문 [MinOrderUSD] 미만이라 **주문 자체가
// 성립하지 않았다.** 문턱은 0.10 인데 실제로는 0.14 부터만 걸리는 상태였다.
// 이 바닥이 그 두 칸을 살린다.
//
// # 대가 — 그 칸에서는 켈리보다 크게 건다
//
//	conf 구간   교정승률   손익분기 대비   켈리 비례   실제    배수
//	0.10~0.12   54.54%    +0.53%p        0.40     1.50   3.8배
//	0.12~0.14   55.27%    +1.26%p        0.95     1.50   1.6배
//
// **0.10~0.12 칸은 여유가 0.53%p 뿐인데 켈리의 3.8배를 건다.** 켈리 초과
// 베팅은 기대값이 양수여도 기하성장률을 깎는다. 이 칸이 전체 회차의 큰
// 비중(2026년 진입의 약 36%)이라 영향이 작지 않다.
//
// 값을 올리면 그 왜곡이 커지고, [MinOrderUSD] 아래로 내리면 두 칸이 다시
// 사라진다. 1.5 는 "최소 주문을 확실히 넘기되 그 이상은 더 걸지 않는다" 의
// 자리다.
const MinStakeUSD = 1.5

// confBins 는 [confWeights] 각 칸의 **하한**이다. 오름차순이고, 마지막 칸은
// 위가 열려 있다.
//
// 첫 칸이 0.10 인 것은 [live.ConfidenceThreshold] 와 같은 값이다. 그보다 낮은
// confidence 에서는 교정 승률이 손익분기 아래라 켈리가 0 이 되므로, 문턱이
// 없어도 이 표가 스스로 0 을 준다 — 문턱과 이 표는 같은 사실의 두 표현이다.
var confBins = [8]float64{0.10, 0.12, 0.14, 0.16, 0.18, 0.20, 0.24, 0.30}

// confWeights 는 각 칸의 목표 비율이다. 최고 칸이 1.0 이 되도록 정규화돼 있다.
var confWeights = [8]float64{0.0792, 0.1891, 0.3479, 0.4525, 0.5657, 0.8545, 0.9296, 1.0000}

// ConfidenceWeight 는 이 confidence 에서 목표 크기가 상한의 몇 배인지 준다.
// 값은 [0, 1] 이다.
//
// confidence 가 첫 칸 아래면 0 이다 — 그 구간은 교정 승률이 손익분기 아래다.
// NaN·Inf·음수도 0 이다(이 패키지의 규칙: 망가진 입력에서는 거래하지 않는다).
//
// 선형 보간하지 않고 **계단**인 것이 의도다. 표의 각 칸은 수만 회차를 모아
// 잰 평균이고, 칸 안에서 승률이 어떻게 움직이는지는 재지 않았다. 보간은
// 재지 않은 것을 아는 척하는 것이고, 칸 경계에서 크기가 튀는 것은 눈에
// 보이지만 잘못된 보간은 보이지 않는다.
func ConfidenceWeight(confidence float64) float64 {
	if !finite(confidence) || confidence < confBins[0] {
		return 0
	}
	w := 0.0
	for i, lo := range confBins {
		if confidence < lo {
			break
		}
		w = confWeights[i]
	}
	return w
}

// StakeTarget 은 이 confidence 에서 걸 명목이다(USD).
//
// 2026-08-17 이전에는 "걸고 싶은 값" 이었고 equity × [CapFraction] 이 그 위에
// 상한으로 얹혀 있었다. 사용자 결정으로 그 상한이 빠지면서 **이 값이 곧 회차당
// 상한**이 됐다. 남은 검사는 [StakeRemaining] 의 가용잔고뿐이다.
//
// 0 을 돌려주면 그 회차는 걸지 않는다.
func StakeTarget(confidence float64) float64 {
	w := ConfidenceWeight(confidence)
	if w <= 0 {
		return 0
	}
	t := MaxStakeUSD * w
	// **바닥은 걸기로 한 회차에만 깐다.** w == 0 인 회차(문턱 아래)는 위에서
	// 이미 0 으로 나갔다 — 그 순서가 뒤집히면 걸지 않기로 한 회차가 바닥값을
	// 받아 최소 주문짜리 베팅이 된다.
	if t < MinStakeUSD {
		t = MinStakeUSD
	}
	if !finite(t) || t <= 0 {
		return 0
	}
	return t
}

// StakeRemaining 은 이 회차에 지금 추가로 걸 수 있는 명목이다.
//
// [Remaining] 의 자리를 대신한다. 다른 점은 기준선이 equity × [CapFraction]
// 이 아니라 [StakeTarget](confidence) 라는 것뿐이고, 실패 방향과 부등호는
// 그대로다:
//
//   - 목표에서 이미 걸린 노출을 뺀다. 정확히 목표면 0 이다 — 목표는 도달해도
//     되는 선이 아니라 넘을 수 없는 선이고, 그 강한 부등호는 [Shares] 가 지킨다.
//   - 노출 항이 하나라도 음수거나 유한하지 않으면 0 이다. 음수 노출은 산술적으로
//     "여유가 더 있다" 로 읽히는데, 그것이야말로 한도를 넘기는 경로다.
//   - **가용잔고를 넘지 않는다.** equity 비례 상한이 빠진 뒤 이것이 자본과
//     주문 크기를 잇는 유일한 끈이다. AvailableUSDT 가 망가졌으면(음수·NaN·Inf)
//     0 이다 — 잔고를 못 읽는 상태에서 절대값 목표를 그대로 거는 것은, 있지도
//     않은 돈으로 베팅하는 것이다.
//
// PositionCost 는 보지 않는다. 그것은 이미 나간 돈이고, 지금 낼 주문이 실제로
// 쓸 수 있는 것은 가용잔고뿐이다.
func StakeRemaining(e Equity, x Exposure, confidence float64) float64 {
	t := StakeTarget(confidence)
	if t <= 0 {
		return 0
	}
	if !finite(e.AvailableUSDT) || e.AvailableUSDT < 0 {
		return 0
	}
	if !finite(x.FilledNotional) || x.FilledNotional < 0 {
		return 0
	}
	if !finite(x.OpenNotional) || x.OpenNotional < 0 {
		return 0
	}
	if !finite(x.PendingCancel) || x.PendingCancel < 0 {
		return 0
	}
	used := x.Total()
	if !finite(used) {
		return 0
	}
	r := t - used
	if r <= 0 {
		return 0
	}
	if r > e.AvailableUSDT {
		r = e.AvailableUSDT
	}
	return r
}
