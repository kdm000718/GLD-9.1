package main

import "time"

// ---------------------------------------------------------------------------
// 시간대 관문 — 정해진 UTC 시각에만 건다
// ---------------------------------------------------------------------------
//
// # 무엇을
//
// 회차 **시작 시각의 UTC 시(hour)** 가 [tradingHours] 에 없으면 그 회차에는
// 아무것도 걸지 않는다. 문턱 미달과 같은 급의 정상 스킵이고, 알람이 아니다.
//
// # 왜 상수인가
//
// 플래그로 빼면 운영 중에 값이 바뀔 수 있고, 그러면 원장의 어떤 줄이 어떤
// 시간대 정책으로 나갔는지 사후에 알 수 없다. `exec.LimitPrice` 와 같은
// 이유다(2026-08-12 사용자 결정). 바꾸려면 이 줄을 고치고 다시 빌드해 배포한다.
//
// # 값의 이력
//
//	12시간   2026-08-15   2,3,6,8,11,12,15,16,17,18,21,22 (사용자 결정)
//	20시간   2026-08-15   06·07·10·12 시만 제외 (사용자 결정)
//	24시간   2026-08-16~  제외 없음 (사용자 결정)
//
// # 왜 다시 24시간인가
//
// 06·07·10·12 를 뺀 근거는 2026년 문턱 0.0714 통과분의 시간대별 판정 승률이
// 손익분기 아래였다는 것뿐이었고, 그 근거가 얼마나 약한지는 그때도 여기 적어
// 두었다: 넷 다 95% 오차막대가 손익분기선을 걸치고(시간대당 700~860회차,
// 오차 ±3.4~3.7%p), 시간대별 편차의 표준편차 1.612%p 는 표본 잡음 예상치
// 1.858%p 보다 **작고**, 카이제곱(df=23) 17.79 는 임계 35.17 에 한참 못
// 미친다 — "시간대별 차이가 없다" 를 기각하지 못한다.
//
// 학습 구간을 바꿔 상위 시간대를 다시 고르면 매번 다른 조합이 나왔고
// (2018~2022 / 2021~2024 / 2023~2025 가 8~10개만 겹친다), 1,961,256개
// 10시간 조합을 전수로 돌렸을 때 표본 안 최고 조합이 표본 밖에서는 중앙값
// 아래(87.5분위)로 떨어졌다. 시간대 선택은 과최적화였다.
//
// 문턱이 0.0714 → 0.14 로 오르면서 근거로 삼았던 그 표조차 대상이 아니게
// 됐다. 다시 24시간으로 되돌린다.
//
// # 관문은 남겨 둔다
//
// 배열을 지우지 않는 이유는 **관문이 있었다는 사실이 코드에 남아야 하기**
// 때문이다. 다시 시간대를 제한할 근거가 생기면 이 배열의 해당 첨자를 false
// 로 바꾸고 다시 빌드해 배포한다. 그때는 위 통계 한계를 먼저 넘겨라.

// tradingHours 는 주문을 내는 UTC 시각이다. 첨자가 곧 시(0..23)다.
//
// 지금은 24개 전부 켜져 있다 — 관문이 사실상 없는 상태다.
//
// **배열로 두는 이유는 첨자가 곧 시이기 때문이다.** 목록으로 두고 순회하면
// 25 나 -1 같은 값이 조용히 "없음" 으로 처리되는데, 배열은 그 자리에서
// 범위를 벗어난다 — [tradingHour] 가 넘기는 값은 언제나 0..23 이다.
var tradingHours = [24]bool{
	0: true, 1: true, 2: true, 3: true,
	4: true, 5: true, 6: true, 7: true,
	8: true, 9: true, 10: true, 11: true,
	12: true, 13: true, 14: true, 15: true,
	16: true, 17: true, 18: true, 19: true,
	20: true, 21: true, 22: true, 23: true,
}

// tradingHourIndex 는 t 가 [tradingHours] 의 몇 번째 칸인지 준다.
//
// **UTC 로 판정한다.** t 가 어떤 위치(Location)를 달고 오든 상관없다 — 서버는
// 도쿄(UTC+9)에 있고, 로컬 시로 재면 정책이 통째로 9시간 밀린다. 회차 시작은
// 언제나 거래소가 준 [live.Round.StartsAt] 이고 그 값은 절대 시각이다.
//
// **이 계산이 [tradingHour] 에서 분리돼 있는 이유는 시험 때문이다.** 표가 24개
// 전부 true 인 동안에는 tradingHour 로 UTC 여부를 잴 수 없다 — 로컬 시로 재도
// 답이 같다. 첨자를 따로 내주면 표의 내용과 무관하게 그 규칙을 못 박을 수 있다.
func tradingHourIndex(t time.Time) int { return t.UTC().Hour() }

// tradingHour 는 이 시각에 주문을 내도 되는지 본다.
func tradingHour(t time.Time) bool {
	return tradingHours[tradingHourIndex(t)]
}
