package main

import "time"

// ---------------------------------------------------------------------------
// 시간대 관문 — 정해진 UTC 시각에만 건다
// ---------------------------------------------------------------------------
//
// # 무엇을
//
// 회차 **시작 시각의 UTC 시(hour)** 가 [tradingHours] 에 없으면 그 회차에는
// 아무것도 걸지 않는다. 문턱 미달과 같은 급의 정상 스킵이고, 알람이 아니다.
//
// # 왜 상수인가
//
// 플래그로 빼면 운영 중에 값이 바뀔 수 있고, 그러면 원장의 어떤 줄이 어떤
// 시간대 정책으로 나갔는지 사후에 알 수 없다. `exec.LimitPrice` 와 같은
// 이유다(2026-08-12 사용자 결정). 바꾸려면 이 줄을 고치고 다시 빌드해 배포한다.
//
// # 값의 이력
//
//	12시간   2026-08-15   2,3,6,8,11,12,15,16,17,18,21,22 (사용자 결정)
//	20시간   2026-08-15~  06·07·10·12 시만 제외 (사용자 결정)
//
// # 왜 이 넷인가
//
// 2026년 백테스트에서 문턱 0.0714 통과분의 **판정** 승률이 손익분기(52.70%)
// 아래로 나온 시간대다:
//
//	UTC 06   52.494%   −0.21%p
//	UTC 07   52.169%   −0.54%p
//	UTC 10   52.211%   −0.49%p
//	UTC 12   51.312%   −1.39%p
//
// 나머지 20개 시간대는 전부 손익분기 위다.
//
// # 이 선택의 한계 — 알고 켠 것이다
//
// **넷 다 95% 오차막대가 손익분기선을 걸친다**(시간대당 700~860회차, 오차
// ±3.4~3.7%p). "적자다" 라고 단정할 수 있는 시간대는 하나도 없다. 시간대별
// 편차의 표준편차 1.612%p 는 표본 잡음 예상치 1.858%p 보다 **작고**,
// 카이제곱(df=23)은 17.79 로 임계 35.17 에 한참 못 미친다 — 통계적으로는
// "시간대별 차이가 없다" 를 기각하지 못한다.
//
// 학습 구간을 바꿔 상위 시간대를 다시 고르면 매번 다른 조합이 나오고
// (2018~2022 / 2021~2024 / 2023~2025 가 8~10개만 겹친다), 표본 밖에서 고른
// "최적" 조합이 그냥 두는 것보다 못한 경우도 있었다.
//
// 그러니 이 제외는 **기대값을 올리려는 것이 아니라 명백한 손실 구간을 피하려는
// 것**으로 읽어야 한다. 실제 효과는 0 일 수 있다.
//
// # 이 관문을 지우려면
//
// [tradingHours] 를 24개 전부 true 로 두면 예전과 같아진다. 배열을 지우지
// 말고 그렇게 하라 — 관문이 있었다는 사실이 코드에 남아야 한다.

// tradingHours 는 주문을 내는 UTC 시각이다. 첨자가 곧 시(0..23)다.
//
// 꺼진 시각: 6, 7, 10, 12 — 나머지 20개는 전부 켜져 있다.
//
// **배열로 두는 이유는 첨자가 곧 시이기 때문이다.** 목록으로 두고 순회하면
// 25 나 -1 같은 값이 조용히 "없음" 으로 처리되는데, 배열은 그 자리에서
// 범위를 벗어난다 — [tradingHour] 가 넘기는 값은 언제나 0..23 이다.
var tradingHours = [24]bool{
	0: true, 1: true, 2: true, 3: true,
	4: true, 5: true, 6: false, 7: false,
	8: true, 9: true, 10: false, 11: true,
	12: false, 13: true, 14: true, 15: true,
	16: true, 17: true, 18: true, 19: true,
	20: true, 21: true, 22: true, 23: true,
}

// tradingHour 는 이 시각에 주문을 내도 되는지 본다.
//
// **UTC 로 판정한다.** t 가 어떤 위치(Location)를 달고 오든 상관없다 — 서버는
// 도쿄(UTC+9)에 있고, 로컬 시로 재면 정책이 통째로 9시간 밀린다. 회차 시작은
// 언제나 거래소가 준 [live.Round.StartsAt] 이고 그 값은 절대 시각이다.
func tradingHour(t time.Time) bool {
	return tradingHours[t.UTC().Hour()]
}
