package main

import "time"

// ---------------------------------------------------------------------------
// 시간대 관문 — 정해진 UTC 시각에만 건다
// ---------------------------------------------------------------------------
//
// # 무엇을
//
// 회차 **시작 시각의 UTC 시(hour)** 가 [tradingHours] 에 없으면 그 회차에는
// 아무것도 걸지 않는다. 문턱 미달과 같은 급의 정상 스킵이고, 알람이 아니다.
//
// # 왜 상수인가
//
// 플래그로 빼면 운영 중에 값이 바뀔 수 있고, 그러면 원장의 어떤 줄이 어떤
// 시간대 정책으로 나갔는지 사후에 알 수 없다. `exec.LimitPrice` 와 같은
// 이유다(2026-08-12 사용자 결정). 바꾸려면 이 줄을 고치고 다시 빌드해 배포한다.
//
// # 근거와 그 한계
//
// 2026년(1/1~8/6) 백테스트, 문턱 0.0172 통과분, 지정가 0.48 전량 체결 가정:
//
//	선택 12시간   24,620회차   52.794%   손익분기 대비 +3.815%p
//	제외 12시간   24,682회차   52.196%   손익분기 대비 +3.216%p
//
// 차이는 +0.60%p 다. **다만 이 선택은 2026년을 포함한 자료를 보고 골랐으므로
// 표본 안이다.** 2023~2025 로만 상위 12시간을 골라 2026 에 시험하면:
//
//	상위 12시간 → 2026  52.829%
//	하위 12시간 → 2026  52.163%      격차 +0.67%p ± 0.45%p  (1.5 SE, p≈0.14)
//
// 표본 밖에서도 부호는 남지만 **유의하지 않다.** 같은 자료를 2023 이후로
// 좁혀 전후반으로 가르면 시간대 순위 상관이 r=+0.005 로 사라진다 — 분할
// 방식에 따라 답이 달라진다는 것 자체가 이 효과가 불안정하다는 뜻이다.
//
// 값어치는 잘 봐야 +0.6%p 이고 0 일 수도 있다. 그 대신 회차가 절반으로 줄어
// 통계적 확신을 얻는 데 걸리는 시간이 두 배가 된다. 그 맞교환을 알고 켠
// 것이다(2026-08-14 사용자 결정).
//
// # 이 관문을 지우려면
//
// [tradingHours] 를 24개 전부 true 로 두면 예전과 같아진다. 배열을 지우지
// 말고 그렇게 하라 — 관문이 있었다는 사실이 코드에 남아야 한다.

// tradingHours 는 주문을 내는 UTC 시각이다. 첨자가 곧 시(0..23)다.
//
// 켜진 시각: 2, 3, 6, 8, 11, 12, 15, 16, 17, 18, 21, 22 (24개 중 12개).
//
// **배열로 두는 이유는 첨자가 곧 시이기 때문이다.** 목록으로 두고 순회하면
// 25 나 -1 같은 값이 조용히 "없음" 으로 처리되는데, 배열은 그 자리에서
// 범위를 벗어난다 — [tradingHour] 가 넘기는 값은 언제나 0..23 이다.
var tradingHours = [24]bool{
	0: false, 1: false, 2: true, 3: true,
	4: false, 5: false, 6: true, 7: false,
	8: true, 9: false, 10: false, 11: true,
	12: true, 13: false, 14: false, 15: true,
	16: true, 17: true, 18: true, 19: false,
	20: false, 21: true, 22: true, 23: false,
}

// tradingHour 는 이 시각에 주문을 내도 되는지 본다.
//
// **UTC 로 판정한다.** t 가 어떤 위치(Location)를 달고 오든 상관없다 — 서버는
// 도쿄(UTC+9)에 있고, 로컬 시로 재면 정책이 통째로 9시간 밀린다. 회차 시작은
// 언제나 거래소가 준 [live.Round.StartsAt] 이고 그 값은 절대 시각이다.
func tradingHour(t time.Time) bool {
	return tradingHours[t.UTC().Hour()]
}
